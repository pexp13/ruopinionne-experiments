"""Промпт первой ступени из статьи Россяйкина (Dialogue 2025), русская версия."""

INSTRUCTION = """Ты эксперт в оценке тональности.
Тебе нужно найти все негативные и позитивные отношения между сущностями в тексте и вывести их в следующем формате:
[источник отношения, объект отношения, выражение в тексте содержащее оценку, оценка (POS/NEG)]
Если источником отношения является автор, то пиши:
['AUTHOR', объект отношения, выражение в тексте содержащее оценку, оценка (POS/NEG)]
Если выраженного источника нет, то пиши:
['NULL', объект отношения, выражение в тексте содержащее оценку, оценка (POS/NEG)]
Допустимо вернуть пустой ответ:
[]
Не нужно давать пояснений к ответу.
Примеры"""


def gold_answer(row):
    """Эталонные кортежи предложения в виде строки-ответа (первый фрагмент каждого поля)."""
    items = [[o["Source"][0][0], o["Target"][0][0], o["Polar_expression"][0][0], o["Polarity"]]
             for o in row["opinions"]]
    return repr(items)


def build_prompt(text, shots):
    """shots — список размеченных предложений, самое похожее идёт последним."""
    parts = [INSTRUCTION]
    for s in shots:
        parts.append(f"Текст: {s['text']}\nОтвет: {gold_answer(s)}")
    parts.append(f"Текст: {text}\nОтвет:")
    return "\n".join(parts)


def build_prompt_stage2(text, shots, suggestions):
    """Вторая ступень: к промпту добавлены ответы других моделей (строки-списки кортежей)."""
    parts = [INSTRUCTION]
    for s in shots:
        parts.append(f"Текст: {s['text']}\nОтвет: {gold_answer(s)}")
    parts.append(f"Текст, который нужно проанализировать:\n{text}")
    parts.append("Ответы экспертов к этому тексту:\n" + "\n".join(suggestions))
    parts.append("Ты можешь выбрать из этих ответов или ответить по-своему.\nТвой ответ:")
    return "\n".join(parts)
